ZONE_NAMES = {
    "DRIFTMOOR": "DRIFTMOOR_TOWN",
    "GREYWATER_VALLEY": "GREYWATER_VALLEY",
}


def load_regions(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")

    def rows(section: str) -> list[list[str]]:
        match = re.search(rf"##\s+{re.escape(section)}\b(.*?)(?=\n##\s+|\Z)", text, re.DOTALL)
        if not match:
            return []
        result = []
        for line in match.group(1).splitlines():
            if not line.strip().startswith("|"):
                continue
            cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
            if cells and cells[0].lower() not in {"id", "name"} and not set(cells[0]) <= {"-", ":"}:
                result.append(cells)
        return result

    points = {row[0]: [float(row[1]), float(row[2])] for row in rows("Points")}
    regions = [
        {"name": row[0], "fill": row[1], "points": row[2].split()}
        for row in rows("Regions")
    ]
    return {"points": points, "regions": regions}


def write_regions(path: Path, data: dict) -> None:
    lines = [
        "# REGIONS.md — Shared Regional Boundary Mesh", "",
        "Generated by `scene_editor.py`. Shared point IDs are intentionally used",
        "by every adjoining face so borders cannot drift apart.", "", "## Points", "",
        "| id | x | y |", "|---|---:|---:|",
    ]
    for point_id, (x, y) in data["points"].items():
        lines.append(f"| {point_id} | {x:g} | {y:g} |")
    lines += ["", "## Regions", "", "| name | fill | points |", "|---|---|---|"]
    for region in data["regions"]:
        lines.append(f"| {region['name']} | {region['fill']} | {' '.join(region['points'])} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_rivers(path: Path) -> list[dict]:
    text = path.read_text(encoding="utf-8")
    match = re.search(r"##\s+Rivers\b(.*?)(?=\n##\s+|\Z)", text, re.DOTALL)
    rivers = []
    for line in (match.group(1).splitlines() if match else []):
        if not line.strip().startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if not cells or cells[0].lower() == "name" or set(cells[0]) <= {"-", ":"}:
            continue
        vertices = [
            [float(x), float(y)]
            for x, y in re.findall(r"\(([-+0-9.]+),\s*([-+0-9.]+)\)", cells[3])
        ]
        rivers.append({"name": cells[0], "color": cells[1], "width": float(cells[2]), "vertices": vertices})
    return rivers


def write_rivers(path: Path, rivers: list[dict]) -> None:
    lines = [
        "# RIVERS.md — Regional Watercourses", "",
        "River centerlines are independent of the shared regional boundary mesh.", "",
        "## Rivers", "", "| name | color | width | vertices |", "|---|---|---:|---|",
    ]
    for river in rivers:
        vertices = " ".join(f"({x:g},{y:g})" for x, y in river["vertices"])
        lines.append(f"| {river['name']} | {river['color']} | {river['width']:g} | {vertices} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_roads(path: Path) -> list[dict]:
    text = path.read_text(encoding="utf-8")
    match = re.search(r"##\s+Roads\b(.*?)(?=\n##\s+|\Z)", text, re.DOTALL)
    out = []
    for line in (match.group(1).splitlines() if match else []):
        cells = [c.strip() for c in line.strip().strip("|").split("|")] if line.strip().startswith("|") else []
        if len(cells) < 5 or cells[0].lower() == "name" or set(cells[0]) <= {"-", ":"}: continue
        verts = [[float(x), float(y)] for x, y in re.findall(r"\(([-+0-9.]+),\s*([-+0-9.]+)\)", cells[4])]
        out.append({"name": cells[0], "kind": cells[1], "color": cells[2], "width": float(cells[3]), "vertices": verts})
    return out


def write_roads(path: Path, roads: list[dict]) -> None:
    lines = ["# ROADS.md — Regional Roads and Trails", "", "## Roads", "", "| name | kind | color | width | vertices |", "|---|---|---|---:|---|"]
    for r in roads:
        verts = " ".join(f"({x:g},{y:g})" for x, y in r["vertices"])
        lines.append(f"| {r['name']} | {r['kind']} | {r['color']} | {r['width']:g} | {verts} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_subzones(path: Path) -> list[dict]:
    text = path.read_text(encoding="utf-8")
    match = re.search(r"##\s+Subzones\b(.*?)(?=\n##\s+|\Z)", text, re.DOTALL)
    out = []
    for line in (match.group(1).splitlines() if match else []):
        cells = [c.strip() for c in line.strip().strip("|").split("|")] if line.strip().startswith("|") else []
        if len(cells) < 3 or cells[0].lower() == "name" or set(cells[0]) <= {"-", ":"}: continue
        verts = [[float(x), float(y)] for x, y in re.findall(r"\(([-+0-9.]+),\s*([-+0-9.]+)\)", cells[2])]
        out.append({"name": cells[0], "fill": cells[1], "vertices": verts})
    return out


def write_subzones(path: Path, zones: list[dict]) -> None:
    lines = ["# SUBZONES.md — Regional Detail Polygons", "", "## Subzones", "", "| name | fill | vertices |", "|---|---|---|"]
    for z in zones:
        verts = " ".join(f"({x:g},{y:g})" for x, y in z["vertices"])
        lines.append(f"| {z['name']} | {z['fill']} | {verts} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_landmarks(path: Path) -> list[dict]:
    text = path.read_text(encoding="utf-8")
    match = re.search(r"##\s+Landmarks\b(.*?)(?=\n##\s+|\Z)", text, re.DOTALL)
    out = []
    for line in (match.group(1).splitlines() if match else []):
        cells = [c.strip() for c in line.strip().strip("|").split("|")] if line.strip().startswith("|") else []
        if len(cells) < 6 or cells[0].lower() == "name" or set(cells[0]) <= {"-", ":"}: continue
        out.append({"name": cells[0], "label": cells[1], "x": float(cells[2]),
                    "y": float(cells[3]), "destination": cells[4],
                    "enabled": cells[5].lower() in {"true", "yes", "1"}})
    return out


def write_landmarks(path: Path, landmarks: list[dict]) -> None:
    lines = ["# LANDMARKS.md — Optional Descendant Landmarks", "", "## Landmarks", "",
             "| name | label | x | y | destination | enabled |", "|---|---|---:|---:|---|---|"]
    for landmark in landmarks:
        enabled = "true" if landmark["enabled"] else "false"
        lines.append(f"| {landmark['name']} | {landmark['label']} | {landmark['x']:g} | "
                     f"{landmark['y']:g} | {landmark['destination']} | {enabled} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def materialize_geometry(geometry_path: Path, data: dict) -> None:
    text = geometry_path.read_text(encoding="utf-8")
    points = data["points"]
    polygons = {
        ZONE_NAMES.get(region["name"], region["name"]):
        " ".join(f"({points[pid][0]:g},{points[pid][1]:g})" for pid in region["points"])
        for region in data["regions"]
    }
    section = re.search(r"(##\s+Zones\b.*?)(?=\n##\s+|\Z)", text, re.DOTALL)
    if not section:
        raise ValueError("GEOMETRY.md has no Zones section")

    def replace(row: re.Match) -> str:
        name = row.group(2).strip()
        if name not in polygons:
            return row.group(0)
        return f"{row.group(1)}{polygons[name]} {row.group(3)}"

    updated = re.sub(
        r"^(\|\s*([^|]+?)\s*\|(?:[^|]*\|){2}\s*)[^|]+(\|\s*)$",
        replace, section.group(1), flags=re.MULTILINE,
    )
    # GREYWATER_VALLEY is new; replace the legacy river-region row on first save.
    if "GREYWATER_VALLEY" not in updated:
        updated = updated.replace("| GREYWATER_RIVER ", "| GREYWATER_VALLEY ", 1)
        updated = re.sub(
            r"^(\|\s*GREYWATER_VALLEY\s*\|(?:[^|]*\|){2}\s*)[^|]+(\|\s*)$",
            lambda m: f"{m.group(1)}{polygons['GREYWATER_VALLEY']} {m.group(2)}",
            updated, flags=re.MULTILINE,
        )
    geometry_path.write_text(text[:section.start(1)] + updated + text[section.end(1):], encoding="utf-8")


